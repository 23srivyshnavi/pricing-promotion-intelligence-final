"""Export generated CSVs as executable MySQL INSERT seed data.
Use on a fresh database after running database/schema.sql.
Run: python -m database.export_csv_sql_seed
"""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
OUT = ROOT / "database" / "seed.sql"

# Explicit order follows parent -> child foreign-key dependencies.
TABLES = [
    ("products.csv", "products", ["product_id","sku","name","category","currency","price_floor","price_ceiling","min_margin_pct","status","created_at"]),
    ("promotions.csv", "promotions", ["promotion_id","name","promotion_type","discount_value","starts_at","ends_at","status","stack_allowed","min_order_value"]),
    ("cost_records.csv", "cost_records", ["cost_id","product_id","unit_cost","currency","effective_from","effective_to","source"]),
    ("promotion_rules.csv", "promotion_rules", ["rule_id","promotion_id","rule_type","rule_value","effective_from","effective_to"]),
    ("price_history.csv", "price_history", ["price_id","product_id","selling_price","effective_at","reason","decision_id","source"]),
    ("competitor_observations.csv", "competitor_observations", ["observation_id","product_id","competitor_name","competitor_price","currency","source_url","source_timestamp","retrieved_at"]),
    ("inventory_snapshots.csv", "inventory_snapshots", ["snapshot_id","product_id","snapshot_date","stock_on_hand","reserved_units","demand_units","stockout"]),
    ("orders.csv", "orders", ["order_id","product_id","quantity","unit_price","discount_amount","order_total","ordered_at","order_status"]),
    ("price_decisions.csv", "price_decisions", ["decision_id","product_id","cost_id","price_id","observation_id","snapshot_id","candidate_price","final_price","discount_pct","margin_pct","decision_status","reason_code","explanation","rule_version","created_at"]),
    ("promotion_products.csv", "promotion_products", ["promotion_id","product_id"]),
    ("audit_events.csv", "audit_events", ["event_id","entity_type","entity_id","event_type","old_state","new_state","reason","event_timestamp","actor"]),
]
NUMERIC = {"product_id","unit_cost","price_floor","price_ceiling","min_margin_pct","discount_value","min_order_value","selling_price","competitor_price","stock_on_hand","reserved_units","demand_units","quantity","unit_price","discount_amount","order_total","candidate_price","final_price","discount_pct","margin_pct"}
BOOLEAN = {"stack_allowed","stockout"}

def sql_value(column, value, sku=None):
    if column == "product_id" and sku is not None:
        return str(int(sku.split("-")[-1]))
    if value is None or value == "":
        return "NULL"
    if column in BOOLEAN:
        return "1" if str(value).strip().lower() in {"1","true","yes"} else "0"
    if column in NUMERIC:
        return str(value)
    return "'" + str(value).replace("\\", "\\\\").replace("'", "\\'").replace("\x00", "") + "'"

def export():
    for filename, _, _ in TABLES:
        if not (DATA / filename).exists():
            raise FileNotFoundError(f"Missing {DATA / filename}; run the generator first.")
    row_count = 0
    with OUT.open("w", encoding="utf-8", newline="\n") as out:
        out.write("-- Generated synthetic SQL seed. Intended for a fresh pricing_intelligence database.\n")
        out.write("-- Apply database/schema.sql first. This file includes sample data generated by the fixed-seed generator.\n")
        out.write("SET FOREIGN_KEY_CHECKS=0;\nSTART TRANSACTION;\n")
        for filename, table, columns in TABLES:
            out.write(f"\n-- {table}\n")
            with (DATA / filename).open("r", encoding="utf-8-sig", newline="") as source:
                reader = csv.DictReader(source)
                for row in reader:
                    sku = row.get("sku")
                    # CSV data stores SKU; MySQL schema stores product_id.
                    values = [sql_value(column, row.get(column), sku=sku) if column != "product_id" else sql_value("product_id", None, sku=sku) for column in columns]
                    col_sql = ", ".join(f"`{column}`" for column in columns)
                    out.write(f"INSERT INTO `{table}` ({col_sql}) VALUES ({', '.join(values)});\n")
                    row_count += 1
        out.write("COMMIT;\nSET FOREIGN_KEY_CHECKS=1;\n")
    return {"file": str(OUT), "rows": row_count, "bytes": OUT.stat().st_size}

if __name__ == "__main__":
    import json
    print(json.dumps(export(), indent=2))
